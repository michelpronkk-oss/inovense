import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import esbuild from "esbuild";

const root = process.cwd();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "auterim-ea-invite-flow-"));
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");

try {
  const { code } = esbuild.transformSync(read("src/lib/early-access/invite-token.ts"), { loader: "ts", format: "esm", target: "node18" });
  const tokenFile = path.join(temp, "invite-token.mjs");
  fs.writeFileSync(tokenFile, code, "utf8");
  const tokens = await import(pathToFileURL(tokenFile).href);
  const token = tokens.createEarlyAccessToken();
  assert.match(token, /^[A-Za-z0-9_-]{43}$/);
  assert.equal(Buffer.from(token, "base64url").length, 32, "invite tokens have 256 bits of entropy");
  assert.equal(tokens.hashEarlyAccessToken(token), crypto.createHash("sha256").update(token).digest("hex"));
  assert.equal(tokens.isEarlyAccessToken("short"), false);
  assert.throws(() => tokens.hashEarlyAccessToken("short"));

  const migration = read("supabase/migrations/20260914_early_access_invites.sql");
  const tableDefinition = migration.match(/create table if not exists public\.os_early_access_invites \(([\s\S]*?)\n\);/)?.[1] ?? "";
  assert.ok(tableDefinition);
  assert.match(tableDefinition, /token_hash text not null unique/);
  assert.doesNotMatch(tableDefinition, /\btoken\s+text\b/i, "the database never stores the bearer token");
  assert.match(migration, /enable row level security/);
  assert.match(migration, /revoke all on table public\.os_early_access_invites from public, anon, authenticated/);
  assert.match(migration, /one_pending_request_uidx/);
  assert.match(migration, /one_active_sent_request_uidx/);
  assert.match(migration, /auth\.users u[\s\S]*?u\.email_confirmed_at/);
  assert.match(migration, /v_email <> v_invite\.email_normalized/);
  assert.match(migration, /for update/);
  assert.match(migration, /public\.provision_initial_workspace\(v_full_name, v_request\.company\)/);
  assert.match(migration, /guard_early_access_accepted_status/);
  assert.match(migration, /grant execute on function public\.accept_early_access_invite\(text\) to authenticated/);
  assert.doesNotMatch(migration, /trial|dodo|subscription/i, "acceptance does not start billing or a trial");
  const finalize = migration.slice(migration.indexOf("create or replace function public.finalize_early_access_invite_send"), migration.indexOf("create or replace function public.fail_early_access_invite_send"));
  assert.ok(finalize.indexOf("set revoked_at = now()") < finalize.indexOf("set delivery_state = 'sent'"), "resend frees the unique active slot before activating the replacement");
  assert.match(finalize, /id <> p_invite_id[\s\S]*delivery_state = 'sent'/, "a successful resend revokes the prior sent token");
  const acceptance = migration.slice(migration.indexOf("create or replace function public.accept_early_access_invite"), migration.indexOf("create or replace function public.guard_early_access_accepted_status"));
  assert.match(acceptance, /if v_invite\.accepted_at is not null[\s\S]*v_invite\.accepted_user_id = v_uid[\s\S]*return query/);
  assert.match(acceptance, /if v_invite\.revoked_at is not null/);
  assert.match(acceptance, /if v_invite\.expires_at <= now\(\)/);
  assert.match(acceptance, /v_email <> v_invite\.email_normalized/);
  assert.match(acceptance, /select \* into v_request[\s\S]*for update[\s\S]*select \* into v_invite[\s\S]*for update/, "duplicate accepts serialize on locked request and invite rows");
  assert.ok(acceptance.indexOf("set accepted_at = now()") < acceptance.indexOf("update public.os_early_access_requests set status = 'accepted'"), "the request status follows real invite consumption in the same transaction");
  const provisioning = read("supabase/migrations/20260905_auth_identity_foundation.sql");
  const initialWorkspaceFunction = provisioning.slice(provisioning.indexOf("create or replace function public.provision_initial_workspace"), provisioning.indexOf("$$;", provisioning.indexOf("create or replace function public.provision_initial_workspace")) + 3);
  assert.match(initialWorkspaceFunction, /pg_advisory_xact_lock\(hashtext\(v_uid::text\)\)/);
  assert.match(initialWorkspaceFunction, /if v_existing_workspace_id is not null[\s\S]*return query/);

  const inviteRoute = read("src/app/app/early-access/accept/route.ts");
  assert.match(inviteRoute, /httpOnly: true/);
  assert.match(inviteRoute, /sameSite: "lax"/);
  assert.match(inviteRoute, /path: TOKEN_COOKIE_PATH/);
  assert.match(inviteRoute, /Cache-Control/);
  assert.match(inviteRoute, /Referrer-Policy/);
  assert.match(inviteRoute, /303/);
  assert.doesNotMatch(inviteRoute, /console\.(?:log|info|warn|error).*token/i);

  const acceptPage = read("src/app/app/early-access/accept/session/page.tsx");
  const acceptAction = read("src/app/app/early-access/accept/session/actions.ts");
  const authCallback = read("src/app/app/auth/callback/route.ts");
  const login = read("src/app/app/login/page.tsx");
  const register = read("src/app/app/register/page.tsx");
  for (const state of ["expired", "revoked", "accepted", "pending", "email-mismatch", "email-unverified"]) assert.ok(acceptPage.includes(state));
  assert.match(acceptPage, /invite\.emailNormalized/);
  assert.match(acceptPage, /user\?\.email_confirmed_at/);
  assert.match(acceptPage, /This invite was issued to a different email address\./);
  assert.match(acceptPage, /acceptEarlyAccessInviteAction/);
  assert.match(acceptAction, /accept_early_access_invite/);
  assert.match(acceptAction, /getVerifiedSupabaseUser/);
  assert.match(acceptAction, /early_access_invite_accepted/);
  assert.match(acceptAction, /redirect\("\/onboarding"\)/);
  assert.match(acceptAction, /continueAfterAcceptedEarlyAccessInviteAction/);
  assert.match(acceptAction, /row\.already_accepted !== true/);
  assert.match(acceptPage, /Continue to your workspace/);
  assert.match(read("src/app/app/onboarding/actions.ts"), /accepted_user_id.*access\.user\.id/);
  assert.match(read("src/app/app/onboarding/page.tsx"), /Welcome to Auterim\./);
  assert.doesNotMatch(acceptAction, /startTrial|trial\/start|checkout|dodo/i);
  assert.match(authCallback, /auth\.verifyOtp/);
  assert.match(authCallback, /EARLY_ACCESS_INVITE_COOKIE/);
  assert.match(authCallback, /early-access\/accept\/session/);
  assert.match(authCallback, /safeNext/);
  assert.match(login, /safeAppPath\(searchParams\.get\("from"\)\)/);
  assert.match(register, /authCallbackHref\(from\)/);
  assert.match(login, /history\.replaceState/);
  assert.match(register, /history\.replaceState/);
  const appLayout = read("src/app/app/layout.tsx");
  assert.match(appLayout, /"\/early-access\/accept\/session"/);
  assert.match(appLayout, /if \(PUBLIC_APP_PATHS\.has\(pathname\)\) return <>\{children\}<\/>/);
  assert.match(read("src/app/app/app-shell.tsx"), /\/early-access\/accept\/session/);

  const adminActions = read("src/app/admin/early-access/actions.ts");
  const email = read("src/lib/email/auth-emails.ts");
  const adminPage = read("src/app/admin/early-access/[id]/page.tsx");
  assert.match(adminActions, /requireInternalAdmin\(\)/);
  assert.match(adminActions, /prepare_early_access_invite/);
  assert.match(adminActions, /finalize_early_access_invite_send/);
  assert.match(adminActions, /fail_early_access_invite_send/);
  assert.match(adminActions, /revoke_early_access_invite/);
  assert.match(adminActions, /new Resend\(apiKey\)/);
  assert.match(adminActions, /hashEarlyAccessToken\(token\)/);
  assert.doesNotMatch(adminActions, /console\.(?:log|info|warn|error).*token/i);
  assert.match(email, /Your Auterim Early Access invite/);
  assert.match(email, /Set up your workspace/);
  assert.match(email, /expires in seven days/);
  assert.match(adminPage, /Approve &amp; send invite/);
  assert.match(adminPage, /Resend invite/);
  assert.match(adminPage, /Revoke invite/);
  assert.match(adminPage, /legacy unverified/);
  assert.match(adminPage, /Open workspace in admin/);

  const attribution = read("src/components/analytics/traffic-attribution-tracker.tsx");
  assert.match(attribution, /sanitizePath\(window\.location\.pathname\)/);
  assert.doesNotMatch(attribution, /window\.location\.href|location\.search\s*\}/, "attribution never transmits a bearer URL");
  assert.match(read("src/app/app/early-access/accept/session/page.tsx"), /robots: \{ index: false/);
  console.log("early-access-invite-flow-smoke: token, SQL, auth, email, admin lifecycle, and privacy contracts passed.");
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
