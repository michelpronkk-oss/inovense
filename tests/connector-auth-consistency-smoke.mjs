import assert from "node:assert/strict";
import fs from "node:fs";

const read = (path) => fs.readFileSync(path, "utf8");
const registry = read("src/lib/connectors/registry.ts");
const truth = read("src/lib/connectors/truth.ts");
const page = read("src/app/app/connectors/page.tsx");
const disconnect = read("src/app/api/connectors/disconnect/route.ts");
const gmail = read("src/lib/connectors/gmail.ts");
const drive = read("src/lib/connectors/google-drive.ts");
const clientFlow = read("src/lib/operators/client-flow/scan.ts");
const operations = read("src/lib/operators/operations/scan.ts");
const clientFlowStatus = read("src/app/api/operators/client-flow/status/route.ts");
const operationsStatus = read("src/app/api/operators/operations/status/route.ts");
const envExample = read(".env.example");

assert.match(registry, /connectorKey: "slack"[\s\S]*authType: "direct_oauth"[\s\S]*status: "available"/);
assert.match(registry, /connectorKey: "trello"[\s\S]*authType: "direct_oauth"[\s\S]*status: "available"/);
assert.match(registry, /connectorKey: "hubspot"[\s\S]*authType: "direct_oauth"[\s\S]*status: "available"/);
assert.match(truth, /connectorKey === SLACK_CONNECTOR_KEY \|\| truth\.connectorKey === TRELLO_CONNECTOR_KEY/);
assert.match(truth, /source: connected \? truth\.source : undefined/);
assert.match(page, /connectorOperatorNames\(connector\.id\)/);
assert.match(page, /Live operators pending/);
assert.match(page, /startDirectConnectorOAuth/);
assert.match(page, /connectorId === "slack" \|\| connectorId === "trello"/);
assert.doesNotMatch(page, /Support Operator.*updateConnectorPermissions/);
assert.match(disconnect, /connectorKey === "google_drive"/);
assert.match(disconnect, /leave Gmail/);
assert.match(disconnect, /\["gmail", "google_drive"[\s\S]*"slack", "trello"\]/);
assert.match(disconnect, /connectorKey === "hubspot" \|\| connectorKey === "slack" \|\| connectorKey === "trello"/);
assert.match(gmail, /includeDriveScope/);
assert.match(gmail, /include_granted_scopes/);
assert.match(drive, /connector_key", "gmail"|connector_key.*gmail/);
assert.match(clientFlow, /connector\.executable === true/);
assert.match(operations, /c\.executable === true/);
assert.match(clientFlowStatus, /slack\?\.executable/);
assert.match(clientFlowStatus, /trello\?\.executable/);
assert.match(operationsStatus, /slack\?\.executable/);
assert.match(operationsStatus, /trello\?\.executable/);
assert.doesNotMatch(envExample, /NANGO_(?:SLACK|TRELLO)_CONFIG_KEY/);
console.log("Connector auth consistency smoke contracts passed.");
