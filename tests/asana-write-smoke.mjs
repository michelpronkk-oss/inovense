import assert from "node:assert/strict";
import fs from "node:fs";
const read = (file) => fs.readFileSync(file, "utf8");
const adapter = read("src/lib/connectors/asana.ts");
const actions = read("src/lib/actions/registry.ts");
const execute = read("src/lib/actions/execute.ts");
const policy = read("src/lib/policies/execution-policy.ts");
const approve = read("src/app/api/approvals/[id]/approve/route.ts");
const scan = read("src/lib/operators/operations/scan.ts");
assert.match(adapter, /createAsanaTask/);
assert.match(adapter, /updateAsanaTask/);
assert.match(adapter, /addAsanaTaskComment/);
assert.match(adapter, /destination_out_of_scope/);
assert.match(adapter, /target_out_of_scope/);
assert.match(adapter, /write_scope_missing/);
assert.match(adapter, /tasks:write/);
assert.match(adapter, /stories:write/);
assert.match(actions, /create_asana_task:[\s\S]*approvalDefault: true/);
assert.match(actions, /update_asana_task:[\s\S]*approvalDefault: true/);
assert.match(actions, /add_asana_comment:[\s\S]*approvalDefault: true/);
assert.match(execute, /action\.connectorKey === "asana"/);
assert.match(policy, /create_asana_task/);
assert.match(policy, /update_asana_task/);
assert.match(approve, /Only Trello, Asana, or Jira actions are executable/);
assert.match(scan, /asana_scan/);
console.log("Asana write smoke checks passed: allowlisted actions, approval-first registry, scope guards, centralized execution, and Operations proposals are wired.");
